def compare_characters():
    """Сравнить список из задачи с существующими персонажами"""

    # Загружаем существующие персонажи
    with open('data/characters-data.json', 'r', encoding='utf-8') as f:
        data = json.load(f)

    existing_names = set()
    for char in data['characters']:
        existing_names.add(char['name'].lower().strip())

    print("=== СРАВНЕНИЕ СПИСКОВ ===")
    print(f"Персонажей в задаче: {len(task_characters)}")
    print(f"Персонажей в JSON: {len(existing_names)}")

    # Находим недостающих
    missing = []
    for name in task_characters:
        if name.lower().strip() not in existing_names:
            missing.append(name)

    # Находим существующих
    existing_in_task = []
    for name in task_characters:
        if name.lower().strip() in existing_names:
            existing_in_task.append(name)

    print(f"\nУже существуют в JSON: {len(existing_in_task)}")
    for name in sorted(existing_in_task):
        print(f"  + {name}")

    print(f"\nНедостающих в JSON: {len(missing)}")
    for name in sorted(missing):
        print(f"  - {name}")

    return missing

if __name__ == "__main__":
    missing = compare_characters()